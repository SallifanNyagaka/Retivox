-- Expiry, lot, barcode, and receipt identity foundation.
-- Aggregate branch_stock remains authoritative during the staged rollout.

ALTER TABLE public.products
  ADD COLUMN IF NOT EXISTS tracks_expiry boolean NOT NULL DEFAULT false;

-- Existing inventory is represented as explicitly untracked stock. This
-- preserves the current quantity without pretending that its expiry is known.
CREATE TABLE IF NOT EXISTS public.inventory_lots (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  business_id uuid NOT NULL REFERENCES public.businesses(id) ON DELETE CASCADE,
  product_id uuid NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  supplier_lot_code text,
  received_at timestamptz NOT NULL DEFAULT now(),
  expires_on date,
  is_untracked_legacy boolean NOT NULL DEFAULT false,
  source_delivery_item_id uuid,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS inventory_lots_one_legacy_per_branchless_product
  ON public.inventory_lots (business_id, product_id)
  WHERE is_untracked_legacy;

CREATE TABLE IF NOT EXISTS public.branch_lot_stock (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  business_id uuid NOT NULL REFERENCES public.businesses(id) ON DELETE CASCADE,
  branch_id uuid NOT NULL REFERENCES public.branches(id) ON DELETE CASCADE,
  product_id uuid NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  lot_id uuid NOT NULL REFERENCES public.inventory_lots(id) ON DELETE RESTRICT,
  base_quantity_on_hand numeric(12,4) NOT NULL DEFAULT 0 CHECK (base_quantity_on_hand >= 0),
  base_quantity_reserved numeric(12,4) NOT NULL DEFAULT 0 CHECK (base_quantity_reserved >= 0),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (branch_id, lot_id)
);

CREATE INDEX IF NOT EXISTS branch_lot_stock_fifo_idx
  ON public.branch_lot_stock (business_id, branch_id, product_id, lot_id);

CREATE INDEX IF NOT EXISTS inventory_lots_expiry_lookup_idx
  ON public.inventory_lots (business_id, product_id, expires_on)
  WHERE expires_on IS NOT NULL AND NOT is_untracked_legacy;

CREATE TABLE IF NOT EXISTS public.product_barcodes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  business_id uuid NOT NULL REFERENCES public.businesses(id) ON DELETE CASCADE,
  product_id uuid NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  uom_id uuid REFERENCES public.units_of_measure(id) ON DELETE RESTRICT,
  code text NOT NULL,
  symbology text NOT NULL DEFAULT 'unknown',
  source text NOT NULL DEFAULT 'manufacturer' CHECK (source IN ('manufacturer', 'internal')),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT product_barcodes_code_nonblank CHECK (length(btrim(code)) BETWEEN 1 AND 128)
);

CREATE UNIQUE INDEX IF NOT EXISTS product_barcodes_normalized_code_uidx
  ON public.product_barcodes (business_id, upper(btrim(code)));

CREATE INDEX IF NOT EXISTS product_barcodes_product_idx
  ON public.product_barcodes (business_id, product_id) WHERE is_active;

-- A sale line may be fulfilled from multiple lots under FEFO allocation.
CREATE TABLE IF NOT EXISTS public.transaction_item_lot_allocations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  business_id uuid NOT NULL REFERENCES public.businesses(id) ON DELETE CASCADE,
  transaction_item_id uuid NOT NULL REFERENCES public.transaction_items(id) ON DELETE CASCADE,
  lot_id uuid NOT NULL REFERENCES public.inventory_lots(id) ON DELETE RESTRICT,
  base_quantity numeric(12,4) NOT NULL CHECK (base_quantity > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (transaction_item_id, lot_id)
);

ALTER TABLE public.supplier_delivery_items
  ADD COLUMN IF NOT EXISTS expires_on date,
  ADD COLUMN IF NOT EXISTS supplier_lot_code text,
  ADD COLUMN IF NOT EXISTS inventory_lot_id uuid REFERENCES public.inventory_lots(id) ON DELETE RESTRICT;

-- Stable receipt key is generated by the client before queueing, so offline
