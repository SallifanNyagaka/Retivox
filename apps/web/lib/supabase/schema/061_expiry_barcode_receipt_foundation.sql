      USING (business_id = public.get_my_business_id());
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='product_barcodes' AND policyname='product_barcodes_business_read') THEN
    CREATE POLICY product_barcodes_business_read ON public.product_barcodes FOR SELECT TO authenticated
      USING (business_id = public.get_my_business_id());
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='transaction_item_lot_allocations' AND policyname='transaction_item_lot_allocations_business_read') THEN
