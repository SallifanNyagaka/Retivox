CREATE UNIQUE INDEX IF NOT EXISTS transactions_business_receipt_number_uidx
  ON public.transactions (business_id, receipt_number)
  WHERE receipt_number IS NOT NULL;

-- Backfill existing positive stock into one explicitly untracked legacy lot.
WITH legacy_lots AS (
  INSERT INTO public.inventory_lots (business_id, product_id, is_untracked_legacy)
  SELECT DISTINCT bs.business_id, bs.product_id, true
    FROM public.branch_stock bs
   WHERE COALESCE(bs.base_quantity_on_hand, bs.quantity_on_hand, 0) > 0
  ON CONFLICT (business_id, product_id) WHERE is_untracked_legacy DO NOTHING
  RETURNING id, business_id, product_id
), all_legacy_lots AS (
  SELECT id, business_id, product_id FROM legacy_lots
  UNION ALL
  SELECT l.id, l.business_id, l.product_id
    FROM public.inventory_lots l
   WHERE l.is_untracked_legacy
)
INSERT INTO public.branch_lot_stock (
  business_id, branch_id, product_id, lot_id, base_quantity_on_hand
)
SELECT bs.business_id,
       bs.branch_id,
       bs.product_id,
       l.id,
       COALESCE(bs.base_quantity_on_hand, bs.quantity_on_hand, 0)
  FROM public.branch_stock bs
  JOIN all_legacy_lots l
    ON l.business_id = bs.business_id
   AND l.product_id = bs.product_id
 WHERE COALESCE(bs.base_quantity_on_hand, bs.quantity_on_hand, 0) > 0
ON CONFLICT (branch_id, lot_id) DO NOTHING;

-- Keep lot stock and aggregate stock auditable while the remaining mutation
-- paths are migrated to FEFO in follow-up changes.
CREATE OR REPLACE VIEW public.branch_lot_stock_reconciliation AS
SELECT bs.business_id,
       bs.branch_id,
       bs.product_id,
       COALESCE(bs.base_quantity_on_hand, bs.quantity_on_hand, 0)::numeric(12,4) AS aggregate_base_quantity,
       COALESCE(SUM(bls.base_quantity_on_hand), 0)::numeric(12,4) AS lot_base_quantity,
       (COALESCE(bs.base_quantity_on_hand, bs.quantity_on_hand, 0)
         - COALESCE(SUM(bls.base_quantity_on_hand), 0))::numeric(12,4) AS difference
  FROM public.branch_stock bs
  LEFT JOIN public.branch_lot_stock bls
    ON bls.business_id = bs.business_id
   AND bls.branch_id = bs.branch_id
   AND bls.product_id = bs.product_id
 GROUP BY bs.business_id, bs.branch_id, bs.product_id,
          bs.base_quantity_on_hand, bs.quantity_on_hand;

-- Alert after 75% of the recorded shelf life has elapsed, while keeping
-- expired stock visible as a separate actionable state.
CREATE OR REPLACE VIEW public.product_expiry_alerts
WITH (security_invoker = true) AS
SELECT bls.business_id,
       bls.branch_id,
       bls.product_id,
       p.name AS product_name,
       p.sku,
       lot.id AS lot_id,
       lot.supplier_lot_code,
       lot.received_at::date AS received_on,
       lot.expires_on,
       bls.base_quantity_on_hand,
       (lot.expires_on - current_date) AS days_remaining,
       CASE
         WHEN lot.expires_on < current_date THEN 'expired'
         ELSE 'expiring_soon'
       END AS alert_status
  FROM public.branch_lot_stock bls
  JOIN public.inventory_lots lot
    ON lot.id = bls.lot_id
   AND lot.business_id = bls.business_id
   AND lot.product_id = bls.product_id
  JOIN public.products p
    ON p.id = bls.product_id
   AND p.business_id = bls.business_id
 WHERE p.tracks_expiry
   AND NOT lot.is_untracked_legacy
   AND lot.expires_on IS NOT NULL
   AND bls.base_quantity_on_hand > 0
   AND (
     lot.expires_on < current_date
     OR (lot.expires_on - current_date)::numeric
          <= GREATEST((lot.expires_on - lot.received_at::date)::numeric * 0.25, 1)
   );

